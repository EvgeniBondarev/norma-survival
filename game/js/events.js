export function pickEvent(g, phase) {
  const pool = DECK.filter((e) => e.phases.includes(phase)
    && e.cond(g)
    && (g.seenEv[e.id] === undefined || g.day - g.seenEv[e.id] >= 5));
  if (!pool.length) return null;
  const e = g.rng.weighted(pool, (x) => x.weight);
  g.seenEv[e.id] = g.day;
  return e;
}

export function pickCrisis(g) {
  const pool = CRISES.filter((e) => e.cond(g)
    && (g.seenEv[e.id] === undefined || g.day - g.seenEv[e.id] >= 4));
  if (!pool.length) return null;
  const e = g.rng.weighted(pool, (x) => x.weight);
  g.seenEv[e.id] = g.day;
  return e;
}

