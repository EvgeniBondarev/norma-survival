        run: (g) => { done.mend = true; return { text: 'Ты зашиваешь рукавицы крученой ниткой и обматываешь ноги чистой тряпкой. Завтра будет чуть теплее.', eff: { rag: -1, wraps: 1, mittens: 1, strength: -2, mended: true } }; },
