export async function runDay(g, io) {
  beginDay(g);
  if (g.pendingLazaret > 0) { g.pendingLazaret--; g.d.lazaret = true; }
  io.hud();
  await io.dayCard(g);
  const consequence = dueConsequences(g);
  if (consequence) await settle(g, io, consequence, null, { kicker: consequence.kicker });
  await playChapter(g, io);
  await playOpening(g, io);
  if (g.singleMeasure?.stage === 'announced') await singleMeasureDay(g, io);
  else if (g.d.cell) await cellDay(g, io);
  else if (g.d.lazaret) await lazaretDay(g, io);
  else for (const p of PHASES) { io.hud(); await p(g, io); }
  const pct = g.d.normPct ?? (g.d.norm ? Math.round((g.d.norm.done / g.d.norm.target) * 100) : 80);
  closeDay(g, pct);
  io.hud();
  await showBrigadeDeaths(g, io);
  await io.morning(g);
}

export async function onDeath(g, io, e) {
  const entry = { num: g.me.num, day: g.day, born: g.me.born, cause: e.cause, text: causeText(e.cause), kind: 'death', ...deathNarration(g, e.cause) };
  g.ledger.push(entry);
  io.saveLedger(g.ledger);
  await io.end({ kind: 'death', entry, g });
  const pct = g.d?.normPct ?? (g.d?.norm ? Math.round((g.d.norm.done / g.d.norm.target) * 100) : 70);
  closeDay(g, pct);
  newLife(g);
}

export async function onEnding(g, io, e) {
  const entry = { num: g.me.num, day: g.day, born: g.me.born, cause: e.cause, text: causeText(e.cause), kind: e.kind };
  g.ledger.push(entry);
  io.saveLedger(g.ledger);
  await io.end({ kind: e.kind, entry, g });
  closeDay(g, g.d?.normPct ?? 70);
  newLife(g);
}

export async function runGame(g, io, { maxDays = Infinity } = {}) {
  while (g.day <= maxDays) {
    try {
      await runDay(g, io);
    } catch (e) {
      if (e instanceof Death) await onDeath(g, io, e);
      else if (e instanceof Ending) await onEnding(g, io, e);
      else throw e;
    }
  }
}

