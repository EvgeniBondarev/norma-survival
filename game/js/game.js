function deathNarration(g, cause) {
  const variants = DEATH_NARRATIONS[cause] || [[`${causeText(cause)}. На %d-й день.`, 'Бригада работает дальше.']];
  g.lastDeathNarration ||= {};
  const previous = g.lastDeathNarration[cause];
  // Это тоже часть мира, заданного `?seed=`: иначе один и тот же
  // прохождённый сценарий заканчивался разными эпитафиями.
  let index = g.rng.int(0, variants.length - 1);
  if (variants.length > 1 && index === previous) index = (index + 1) % variants.length;
  g.lastDeathNarration[cause] = index;
  return { epitaph: variants[index][0].replace('%d', String(g.day - g.me.born + 1)), aftermath: variants[index][1] };
}

// ---------- шаги ----------
export async function step(g, io, spec) {
  const avail = spec.choices.filter((c) => !c.show || c.show(g));
  const idx = await io.choose({
    kicker: spec.kicker,
    text: typeof spec.text === 'function' ? spec.text(g) : spec.text,
    img: spec.img,
    norm: spec.norm,
    item: spec.item,
    reigns: !!spec.reigns,
    choices: avail.map((c) => ({
      label: c.label,
      sub: typeof c.sub === 'function' ? c.sub(g) : c.sub,
      disabled: c.ok ? !c.ok(g) : false,
    })),
  });
  const c = avail[idx];
  const before = snapshot(g);
  const r = (await c.run(g, io)) || {};
  return settle(g, io, r, before, spec);
}

// Применяет итог выбора и показывает результат. Смерть и финалы показываем после текста.
export async function settle(g, io, r, before, spec = {}) {
  before = before || snapshot(g);
  if (r.cell) g.pendingCell = true;
  if (r.lazaret) g.pendingLazaret = r.lazaret;
  if (r.trace) addTrace(g, r.trace);
  if (r.debt) addDebt(g, r.debt);
  if (r.mark) addMark(g, r.mark);
  let err = null;
  try {
    if (r.eff) apply(g, r.eff);
    if (r.die) throw new Death(r.die);
    if (r.end) throw new Ending(r.end, r.cause);
  } catch (e) { err = e; }
  await io.result({ text: r.text, deltas: diff(before, g), final: !!err, kicker: spec.kicker, img: r.img || spec.img,
    speaker: r.speaker || spec.speaker,
    trace: r.trace?.text || r.notice || (r.mark ? `Отметка: ${r.mark.text}.` : '') || (r.debt ? `Долг: ${r.debt.text || r.debt.type}.` : '') });
  if (err) throw err;
  if (r.note) await io.note(r.note);
  if (r.next === 'extended') {
    const sp = SPECIAL.extended;
    await step(g, io, { kicker: sp.kicker, text: sp.text, img: sp.img, choices: sp.choices });
  }
  return r;
}

async function playEvent(g, io, e) {
  g.d.events++;
  io.sfx('event');
  return step(g, io, { kicker: e.kicker, text: e.text, img: e.img, choices: e.choices });
}

async function maybeEvent(g, io, phase, p) {
  if (g.d.events >= 4) return;
  if (!g.rng.chance(p)) return;
  const e = pickEvent(g, phase);
  if (e) await playEvent(g, io, e);
}

async function maybeCrisis(g, io) {
  if (g.d.crisis || !g.rng.chance(0.68)) return;
  const e = pickCrisis(g);
  if (!e) return;
  g.d.crisis = true;
  io.sfx('event');
  await step(g, io, { kicker: e.kicker, text: e.text, choices: e.choices, reigns: true });
}

