function npcOutput(g, pace) {
  let total = 0;
  const base = g.trust >= 2 ? 1.05 : g.trust <= -2 ? 0.92 : 1;
  for (const n of alive(g)) {
    total += (0.35 + 0.65 * (n.hp / 100)) * base * g.rng.range(0.85, 1.1)
      * (g.brigadier.trait === 'harsh' ? 1.08 : 1) * (pace === 'slow' ? 0.97 : 1);
  }
  return total;
}

