  if (s.satiety < 35) f.hunger++; else f.hunger = Math.max(0, f.hunger - 1);
  if (f.hunger >= 6 && g.day >= 12 && f.scurvy < 3) { f.scurvy++; f.hunger = 3; }
  if (s.warmth < 35 && coldMod(g) > 1.05 && g.rng.chance(0.36 + pressure * 0.1)) { f.frostbite = Math.min(3, f.frostbite + 1); }
